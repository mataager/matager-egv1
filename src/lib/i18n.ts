export type DashboardTranslations = typeof dashboardTranslations.en;

interface DashboardLanguageContextType {
  locale: Locale;
  dir: Direction;
  setLocale: (locale: Locale) => void;
  toggleLocale: () => void;
  t: DashboardTranslations;
}

const DashboardLanguageContext = createContext<DashboardLanguageContextType | undefined>(undefined);

export const DASHBOARD_LOCALE_STORAGE_KEY = "matager-locale";

export const DashboardLanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [locale, setLocaleState] = useState<Locale>("en");
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    try {
      const stored = localStorage.getItem(DASHBOARD_LOCALE_STORAGE_KEY) as Locale | null;
      if (stored === "en" || stored === "ar") {
        setLocaleState(stored);
      }
    } catch {
      // Storage unavailable
    }
    setMounted(true);
  }, []);

  const dir: Direction = locale === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    if (!mounted) return;
    const root = document.documentElement;
    root.setAttribute("lang", locale);
    root.setAttribute("dir", dir);
    try {
      localStorage.setItem(DASHBOARD_LOCALE_STORAGE_KEY, locale);
    } catch {
      // Storage blocked
    }
  }, [locale, dir, mounted]);

  const toggleLocale = useCallback(() => {
    setLocaleState((prev) => (prev === "en" ? "ar" : "en"));
  }, []);

  const value = useMemo(
    () => ({
      locale,
      dir,
      setLocale: setLocaleState,
      toggleLocale,
      t: dashboardTranslations[locale],
    }),
    [locale, dir, toggleLocale]
  );

  return React.createElement(
    DashboardLanguageContext.Provider,
    { value },
    children
  );
};

export function useDashboardLanguage(): DashboardLanguageContextType {
  const context = useContext(DashboardLanguageContext);
  if (!context) {
    // Fallback if rendered outside of DashboardLanguageProvider
    return {
      locale: "en",
      dir: "ltr",
      setLocale: () => {},
      toggleLocale: () => {},
      t: dashboardTranslations.en,
    };
  }
  return context;
}
